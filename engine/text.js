function glyph3(ch) {
  if (ch in F3_NARROW) { const g = F3_NARROW[ch]; return g ? [...g].map((b) => [b === '1']) : [[false], [false], [false], [false], [false]]; }
  const g = F3[ch] ?? F3['?'];
  return [0, 1, 2, 3, 4].map((r) => [0, 1, 2].map((c) => g[r * 3 + c] === '1'));
}
function glyph5(ch) { const g = F5[ch] ?? F5['?']; return g.map((row) => [...row].map((c) => c === '#')); }
const textCache = new Map();
/** Pixel text as a little canvas (one pixel per font pixel), with a dark drop shadow. (SWARM GEMS uses it too.) */
export function textArt(str, col, big = false, shadow = INK) {
  const k = `${big ? 5 : 3}|${col}|${shadow}|${str}`;
  if (textCache.has(k)) return textCache.get(k);
  const glyphs = [...String(str).toUpperCase()].map(big ? glyph5 : glyph3);
  const w = glyphs.reduce((n, gl) => n + gl[0].length + 1, 0), h = big ? 7 : 5;
  const c = canvas(Math.max(1, w + 1), h + 1), g = c.getContext('2d');
  for (const [dx, dy, fill] of shadow ? [[1, 1, shadow], [0, 0, col]] : [[0, 0, col]]) {
    g.fillStyle = fill; let x = 0;
    for (const gl of glyphs) { gl.forEach((row, y) => row.forEach((on, i) => { if (on) g.fillRect(x + i + dx, y + dy, 1, 1); })); x += gl[0].length + 1; }
  }
  if (textCache.size > 400) textCache.clear();
  textCache.set(k, c);
  return c;
}
function canvas(w, h) { const c = document.createElement('canvas'); c.width = w; c.height = h; return c; }

